"""Disk declarations: what ``[modules.disks.mounts.<name>]`` may say and the fstab text it becomes.

Accessed via: ``modules/disks/disks`` (check / install) and ``adapters/disks.py`` (capture proposals).

Assumptions: pure, no I/O. The device is named by a udev symlink (``/dev/disk/by-uuid/<uuid>``, ``by-label``,
``by-partuuid``) so systemd waits for exactly that device and a re-plugged USB disk that came back as ``sdb``
still mounts. Every entry is ``nofail`` (a missing disk never stops the boot) and, unless the declaration says
otherwise, ``x-systemd.automount`` (mounted on first access, so an unplugged disk costs nothing).

Filesystems (``FILESYSTEMS``): ext2/3/4, xfs, btrfs, f2fs, exfat, vfat, hfsplus, udf, iso9660 mount through the
kernel; ``ntfs`` through ``ntfs3`` (kernel) or ``ntfs-3g``; ``apfs`` through ``apfs-fuse`` (read-only, userspace) or
the ``linux-apfs-rw`` kernel module (DKMS; read-write only when the declaration says ``read_only = false``).
Read-only is the default for the filesystems whose Linux write support can damage a disk that another OS owns
(ntfs, apfs, hfsplus, udf, iso9660).

Public API:

- ``DiskSpec`` (frozen) and ``parse_disks(options, *, home) -> list[DiskSpec]`` (``ConfigError`` names the key).
- ``resolve_driver(spec, *, kernel_apfs) -> str``: the driver that will mount ``spec`` (``auto`` resolved).
- ``fstab_entry(spec, driver, ids) -> str`` and ``fstab_block(entries) -> str``; ``merge_fstab(text, block)``;
  ``managed_lines(text)``; ``foreign_references(text, spec)``: the managed block and the lines outside it that
  already name the same device or mount point.
- ``unit_name(path, suffix)``: ``systemd-escape -p --suffix`` for a mount point.
- ``udev_encode(label)``, ``fstab_escape(text)``.
- ``PINNED_APFS_FUSE`` (the source the module builds, by commit) and ``APFS_DKMS_PACKAGE`` (Ubuntu's DKMS package).
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import PurePosixPath

from ubuntu_tweaks.errors import ConfigError

MARK_BEGIN = "# BEGIN ubuntu-tweaks disks"
MARK_END = "# END ubuntu-tweaks disks"
BLOCK_NOTE = " (generated by `ubuntu-tweak apply` from [modules.disks.mounts] in the profile; edit the profile)"

DEFAULT_DEVICE_TIMEOUT = "10s"
SELECTORS = {"uuid": "by-uuid", "label": "by-label", "partuuid": "by-partuuid"}
_NAME = re.compile(r"[a-z0-9][a-z0-9._-]*")
_IDENT = re.compile(r"[0-9A-Za-z][0-9A-Za-z._:=+@ #-]*")
_PATH = re.compile(r"/[A-Za-z0-9._@+/-]*")
_TIMEOUT = re.compile(r"[0-9]+(?:ms|s|min|m|h)?")
_OPTION = re.compile(r"[A-Za-z0-9_][A-Za-z0-9_.:=@+/-]*")
_RESERVED = {"ro", "rw", "defaults", "auto", "noauto", "user", "users", "nofail", "uid", "gid", "readwrite"}
_FORBIDDEN_MOUNTPOINTS = {"/", "/home", "/root", "/var", "/opt", "/srv", "/tmp"}
_FORBIDDEN_PREFIXES = ("/boot", "/etc", "/usr", "/bin", "/sbin", "/lib", "/proc", "/sys", "/dev", "/run", "/snap")
_FIELDS = {
    "uuid",
    "label",
    "partuuid",
    "fstype",
    "driver",
    "mountpoint",
    "read_only",
    "owner",
    "automount",
    "device_timeout",
    "idle_timeout",
    "volume",
    "options",
    "description",
}

# apfs-fuse 2023-03-12, upstream's last commit, pinned by commit so a moved branch changes nothing silently; a new
# pin makes the module's check report drift and rebuild. Nothing packages apfs-fuse for Ubuntu 26.04.
PINNED_APFS_FUSE = ("https://github.com/sgan81/apfs-fuse", "66b86bd525e8cb90f9012543be89b1f092b75cf3")
APFS_DKMS_PACKAGE = "apfs-dkms"  # Ubuntu universe: linux-apfs-rw 0.3.18, builds against kernel 7.0.0-38 (tested)


@dataclass(frozen=True)
class Filesystem:
    drivers: tuple[str, ...]  # the first one is the default
    read_only_default: bool
    owner_options: tuple[str, ...] = ()  # templates with {uid} and {gid}; empty: the filesystem keeps its own owners


_UNIX_OWNER = ("uid={uid}", "gid={gid}", "umask=022")
FILESYSTEMS: dict[str, Filesystem] = {
    "ext2": Filesystem(("kernel",), False),
    "ext3": Filesystem(("kernel",), False),
    "ext4": Filesystem(("kernel",), False),
    "xfs": Filesystem(("kernel",), False),
    "btrfs": Filesystem(("kernel",), False),
    "f2fs": Filesystem(("kernel",), False),
    "exfat": Filesystem(("kernel",), False, _UNIX_OWNER),
    "vfat": Filesystem(("kernel",), False, _UNIX_OWNER),
    "ntfs": Filesystem(("ntfs3", "ntfs-3g"), True, _UNIX_OWNER),
    "hfsplus": Filesystem(("kernel",), True, _UNIX_OWNER),
    "udf": Filesystem(("kernel",), True, ("uid={uid}", "gid={gid}")),
    "iso9660": Filesystem(("kernel",), True, ("uid={uid}", "gid={gid}")),
    "apfs": Filesystem(("auto", "fuse", "kernel"), True, ("uid={uid}", "gid={gid}")),
}


@dataclass(frozen=True)
class DiskSpec:
    name: str
    selector: str  # uuid | label | partuuid
    ident: str
    fstype: str
    driver: str  # as declared; ``auto`` is resolved by ``resolve_driver``
    mountpoint: str
    read_only: bool
    owner: str | None  # None: the desktop user
    automount: bool
    device_timeout: str
    idle_timeout: str | None
    volume: int
    options: tuple[str, ...]
    description: str

    @property
    def source(self) -> str:
        """The udev symlink of the device (not fstab-escaped)."""
        ident = udev_encode(self.ident) if self.selector == "label" else self.ident
        return f"/dev/disk/{SELECTORS[self.selector]}/{ident}"

    @property
    def maps_owner(self) -> bool:
        return bool(FILESYSTEMS[self.fstype].owner_options)


def udev_encode(text: str) -> str:
    """udev's name for a label inside ``/dev/disk/by-label``: everything but ``[0-9A-Za-z#+-.:=@_]`` as ``\\xHH``."""
    safe = set("#+-.:=@_")
    return "".join(
        char
        if char.isascii() and (char.isalnum() or char in safe)
        else "".join(f"\\x{byte:02x}" for byte in char.encode())
        for char in text
    )


def fstab_escape(text: str) -> str:
    """The characters that would split an fstab field, as the octal escapes ``mount`` reads back."""
    return "".join({" ": "\\040", "\t": "\\011", "\n": "\\012", "\\": "\\134"}.get(char, char) for char in text)


def fstab_unescape(text: str) -> str:
    return re.sub(r"\\([0-7]{3})", lambda found: chr(int(found.group(1), 8)), text)


def unit_name(path: str, suffix: str) -> str:
    """``systemd-escape --path --suffix=<suffix> <path>`` (``/mnt/mac-backups`` -> ``mnt-mac\\x2dbackups.mount``)."""
    trimmed = "/".join(part for part in path.split("/") if part)
    if not trimmed:
        return f"-.{suffix}"
    out: list[str] = []
    for index, char in enumerate(trimmed):
        if char == "/":
            out.append("-")
        elif char.isascii() and (char.isalnum() or char in ":_" or (char == "." and index > 0)):
            out.append(char)
        else:
            out.append("".join(f"\\x{byte:02x}" for byte in char.encode()))
    return "".join(out) + "." + suffix


def _fail(name: str, message: str) -> ConfigError:
    return ConfigError(f"[modules.disks.mounts.{name}] {message}")


def _text(name: str, table: Mapping[str, object], key: str) -> str | None:
    value = table.get(key)
    if value is None:
        return None
    if not isinstance(value, str) or not value.strip():
        raise _fail(name, f"{key} must be a non-empty string, got {value!r}")
    return value


def _flag(name: str, table: Mapping[str, object], key: str, default: bool) -> bool:
    value = table.get(key, default)
    if not isinstance(value, bool):
        raise _fail(name, f"{key} must be true or false, got {value!r}")
    return value


def _mountpoint(name: str, raw: str | None, home: str) -> str:
    if raw is None:
        return f"/mnt/{name}"
    path = raw
    if path == "~" or path.startswith("~/"):
        path = home.rstrip("/") + path[1:]
        if path.rstrip("/") == home.rstrip("/"):
            raise _fail(name, "mountpoint must be a directory inside your home, not the home directory itself")
    if not _PATH.fullmatch(path):
        raise _fail(name, f"mountpoint {raw!r} must be an absolute path of letters, digits and . _ - + @ /")
    segments = path.rstrip("/").split("/")[1:]
    if ".." in segments or "." in segments or "" in segments:
        raise _fail(name, f"mountpoint {raw!r} must not contain '.', '..' or empty segments")
    clean = str(PurePosixPath(path))
    if clean in _FORBIDDEN_MOUNTPOINTS or any(clean == p or clean.startswith(p + "/") for p in _FORBIDDEN_PREFIXES):
        raise _fail(name, f"mountpoint {clean} is a system directory: use /mnt/<name> or a directory of your own")
    return clean


def _options(name: str, value: object) -> tuple[str, ...]:
    if value is None:
        return ()
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise _fail(name, f"options must be a list of strings, got {value!r}")
    for option in value:
        key = option.split("=", 1)[0]
        if not _OPTION.fullmatch(option) or key in _RESERVED or key.startswith("x-systemd."):
            raise _fail(
                name,
                f"option {option!r} is not allowed here (read_only, owner, automount, device_timeout and "
                "idle_timeout have their own keys; options carries the rest)",
            )
    return tuple(value)


def _parse_one(name: str, table: object, home: str) -> DiskSpec:
    if not _NAME.fullmatch(name):
        raise ConfigError(f"[modules.disks.mounts.{name}] the name must be lowercase letters, digits, . _ -")
    if not isinstance(table, dict):
        raise _fail(name, "must be a table")
    unknown = sorted(set(table) - _FIELDS)
    if unknown:
        raise _fail(name, f"unknown key(s): {', '.join(unknown)}")
    chosen = [key for key in SELECTORS if key in table]
    if len(chosen) != 1:
        raise _fail(name, "name the device with exactly one of uuid, label or partuuid")
    selector = chosen[0]
    ident = _text(name, table, selector)
    if ident is None or not _IDENT.fullmatch(ident) or (selector != "label" and " " in ident):
        raise _fail(name, f"{selector} {ident!r} is not a valid identifier")
    fstype = _text(name, table, "fstype")
    if fstype is None:
        raise _fail(name, f"fstype is required ({', '.join(sorted(FILESYSTEMS))})")
    if fstype not in FILESYSTEMS:
        raise _fail(name, f"fstype {fstype!r} is not supported; supported: {', '.join(sorted(FILESYSTEMS))}")
    filesystem = FILESYSTEMS[fstype]
    driver = _text(name, table, "driver") or filesystem.drivers[0]
    if driver not in filesystem.drivers:
        raise _fail(
            name, f"driver {driver!r} is not available for {fstype}; use one of {', '.join(filesystem.drivers)}"
        )
    volume = table.get("volume", 0)
    if isinstance(volume, bool) or not isinstance(volume, int) or volume < 0:
        raise _fail(name, f"volume must be a non-negative integer, got {volume!r}")
    if volume and fstype != "apfs":
        raise _fail(name, "volume only applies to apfs containers")
    device_timeout = _text(name, table, "device_timeout") or DEFAULT_DEVICE_TIMEOUT
    idle_timeout = _text(name, table, "idle_timeout")
    for key, value in (("device_timeout", device_timeout), ("idle_timeout", idle_timeout)):
        if value is not None and not _TIMEOUT.fullmatch(value):
            raise _fail(name, f"{key} {value!r} must look like 10s, 2min or 0")
    owner = _text(name, table, "owner")
    if owner is not None and not filesystem.owner_options:
        raise _fail(name, f"{fstype} keeps its own file owners: owner does not apply")
    return DiskSpec(
        name=name,
        selector=selector,
        ident=ident,
        fstype=fstype,
        driver=driver,
        mountpoint=_mountpoint(name, _text(name, table, "mountpoint"), home),
        read_only=_flag(name, table, "read_only", filesystem.read_only_default),
        owner=owner,
        automount=_flag(name, table, "automount", True),
        device_timeout=device_timeout,
        idle_timeout=idle_timeout,
        volume=volume,
        options=_options(name, table.get("options")),
        description=_text(name, table, "description") or "",
    )


def parse_disks(options: Mapping[str, object], *, home: str) -> list[DiskSpec]:
    """The ``[modules.disks]`` table (the module's options) as specs, in name order; every error names its key."""
    unknown = sorted(set(options) - {"mounts"})
    if unknown:
        raise ConfigError(f"[modules.disks] unknown option(s): {', '.join(unknown)}")
    mounts = options.get("mounts", {})
    if not isinstance(mounts, dict):
        raise ConfigError("[modules.disks.mounts] must be a table of [modules.disks.mounts.<name>] tables")
    specs = [_parse_one(name, mounts[name], home) for name in sorted(mounts)]
    for field in ("mountpoint", "source"):
        seen: dict[str, str] = {}
        for spec in specs:
            value = getattr(spec, field)
            if value in seen:
                raise ConfigError(
                    f"[modules.disks.mounts] {seen[value]} and {spec.name} share the same {field} {value}"
                )
            seen[value] = spec.name
    return specs


def resolve_driver(spec: DiskSpec, *, kernel_apfs: bool) -> str:
    """The driver that mounts ``spec``. ``auto`` (apfs) picks the kernel module when it is already loadable or
    write access was asked for, else the read-only FUSE driver; any other filesystem has one default."""
    if spec.fstype != "apfs":
        return spec.driver
    if spec.driver != "auto":
        return spec.driver
    return "kernel" if kernel_apfs or not spec.read_only else "fuse"


def fstab_type(spec: DiskSpec, driver: str) -> str:
    if spec.fstype == "ntfs":
        return "ntfs3" if driver == "ntfs3" else "ntfs-3g"
    if spec.fstype == "apfs":
        return "fuse.apfs-fuse" if driver == "fuse" else "apfs"
    return spec.fstype


def mount_options(spec: DiskSpec, driver: str, ids: tuple[int, int] | None) -> list[str]:
    """The fstab option list: access mode, owner mapping, driver specifics, extras, then systemd's."""
    if spec.fstype == "apfs" and driver == "fuse" and not spec.read_only:
        raise ConfigError(
            f"[modules.disks.mounts.{spec.name}] apfs-fuse cannot write: declare read_only = true, or "
            'driver = "kernel" for the experimental read-write kernel module'
        )
    options = ["ro" if spec.read_only else "rw"]
    if spec.maps_owner:
        if ids is None:
            raise ConfigError(f"[modules.disks.mounts.{spec.name}] cannot tell which user owns the files: set owner")
        uid, gid = ids
        options += [template.format(uid=uid, gid=gid) for template in FILESYSTEMS[spec.fstype].owner_options]
    if spec.fstype == "apfs":
        if driver == "fuse":
            options.insert(1, "allow_other")
        elif not spec.read_only:
            options.append("readwrite")
        if spec.volume:
            options.append(f"vol={spec.volume}")
    options += spec.options
    options.append("nofail")
    if spec.automount:
        options.append("x-systemd.automount")
    options.append(f"x-systemd.device-timeout={spec.device_timeout}")
    if spec.idle_timeout is not None:
        options.append(f"x-systemd.idle-timeout={spec.idle_timeout}")
    return options


def fstab_entry(spec: DiskSpec, driver: str, ids: tuple[int, int] | None) -> str:
    fields = [
        fstab_escape(spec.source),
        fstab_escape(spec.mountpoint),
        fstab_type(spec, driver),
        ",".join(mount_options(spec, driver, ids)),
        "0",
        "0",
    ]
    return " ".join(fields)


def describe(spec: DiskSpec, driver: str) -> str:
    """One comment line above an entry: what it is, in words."""
    access = "read-only" if spec.read_only else "read-write"
    how = f"{spec.fstype}, {driver}, {access}" if spec.fstype in ("apfs", "ntfs") else f"{spec.fstype}, {access}"
    return f"# {spec.name}: {spec.description + ' (' + how + ')' if spec.description else how}"


def fstab_block(entries: Sequence[tuple[DiskSpec, str, str]]) -> str:
    """The managed block for ``(spec, driver, entry line)`` triples; ``""`` when there is nothing to manage."""
    if not entries:
        return ""
    lines = [MARK_BEGIN + BLOCK_NOTE]
    for spec, driver, entry in entries:
        lines += [describe(spec, driver), entry]
    lines.append(MARK_END)
    return "\n".join(lines) + "\n"


def _block_span(lines: Sequence[str]) -> tuple[int, int] | None:
    begin = next((i for i, line in enumerate(lines) if line.startswith(MARK_BEGIN)), None)
    if begin is None:
        return None
    end = next((i for i in range(begin + 1, len(lines)) if lines[i].startswith(MARK_END)), None)
    if end is None:
        raise ConfigError("/etc/fstab has a '# BEGIN ubuntu-tweaks disks' line without its END: repair it by hand")
    return begin, end


def managed_lines(text: str) -> list[str] | None:
    """The entry lines of the managed block (comments dropped); ``None`` when the file has no block."""
    lines = text.splitlines()
    span = _block_span(lines)
    if span is None:
        return None
    return [line for line in lines[span[0] + 1 : span[1]] if line.strip() and not line.lstrip().startswith("#")]


def merge_fstab(text: str, block: str) -> str:
    """``text`` with the managed block replaced by ``block`` (removed when empty, appended when new)."""
    lines = text.splitlines()
    span = _block_span(lines)
    new = block.splitlines()
    if span is not None:
        head, tail = lines[: span[0]], lines[span[1] + 1 :]
        if not new and not any(line.strip() for line in tail):
            while head and not head[-1].strip():  # the blank line that set the block apart goes with it
                head.pop()
        merged = head + new + tail
    elif new:
        merged = lines + ([""] if lines and lines[-1].strip() else []) + new
    else:
        merged = lines
    return "\n".join(merged) + ("\n" if merged else "")


def foreign_references(text: str, spec: DiskSpec) -> list[int]:
    """1-based line numbers outside the managed block that mount the same device or use the same mount point."""
    lines = text.splitlines()
    span = _block_span(lines)
    found: list[int] = []
    tags = {f"{spec.selector.upper()}={spec.ident}", spec.source}
    for number, line in enumerate(lines, start=1):
        if span is not None and span[0] < number - 1 < span[1]:
            continue
        fields = line.split()
        if len(fields) < 2 or fields[0].startswith("#"):
            continue
        source, target = fstab_unescape(fields[0]), fstab_unescape(fields[1])
        if source in tags or target.rstrip("/") == spec.mountpoint:
            found.append(number)
    return found
